export const getFaqMatch = (input, uiLang) => {
  const query = input.toLowerCase();
  const isDevanagari = /[\u0900-\u097F]/.test(query);

  let bestMatch = null;
  let highestScore = 0;

  // Initial guess based on script or UI language
  let detectedLang = isDevanagari ? 'hi' : 'en';
  if (isDevanagari && uiLang === 'mr') detectedLang = 'mr';
  if (!isDevanagari && uiLang !== 'en') detectedLang = uiLang;

  for (const faq of faqDatabase) {
    let enScore = 0, hiScore = 0, mrScore = 0;

    // Check English Keywords
    for (const kw of faq.en_kw) {
      if (query.includes(kw.toLowerCase())) enScore += kw.split(' ').length;
    }
    // Check Hindi Keywords
    for (const kw of faq.hi_kw) {
      if (query.includes(kw.toLowerCase())) hiScore += kw.split(' ').length;
    }
    // Check Marathi Keywords
    for (const kw of faq.mr_kw) {
      if (query.includes(kw.toLowerCase())) mrScore += kw.split(' ').length;
    }

    const maxKwScore = Math.max(enScore, hiScore, mrScore);

    if (maxKwScore > highestScore) {
      highestScore = maxKwScore;
      bestMatch = faq;

      // Update detected language based on which keywords matched best
      if (hiScore > enScore && hiScore >= mrScore) {
        detectedLang = 'hi';
      } else if (mrScore > enScore && mrScore > hiScore) {
        detectedLang = 'mr';
      } else if (enScore >= hiScore && enScore >= mrScore) {
        detectedLang = 'en';
      }
    }
  }

  // If a solid match is found
  if (highestScore > 0 && bestMatch) {
    return {
      content: bestMatch[detectedLang] || bestMatch['en'],
      lang: detectedLang
    };
  }

  // Fallback response if no match found
  const fallbacks = {
    hi: "क्षमा करें, मुझे इसके बारे में जानकारी नहीं है। कृपया टीबी के लक्षणों या उपचार के बारे में पूछें।",
    mr: "क्षमस्व, मला याबद्दल माहिती नाही. कृपया टीबीची लक्षणे किंवा उपचारांबद्दल विचारा.",
    en: "I'm sorry, I don't have specific information on that. Try asking about TB symptoms, diagnosis, or treatment."
  };

  return {
    content: fallbacks[detectedLang] || fallbacks['en'],
    lang: detectedLang
  };
};
